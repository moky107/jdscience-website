from l3_nervous.narration import BY_SLUG


def _lesson(slug: str, slides: list[dict], reveals: list[dict], animate: set[str] | None = None) -> dict:
    script = BY_SLUG[slug]
    return {
        "slug": slug,
        "spec": script.spec,
        "title": script.title,
        "subtitle": script.subtitle,
        "filename": script.filename,
        "youtube_filename": script.youtube_filename,
        "tier": script.tier,
        "series": script.series,
        "part": script.part,
        "pages": max(s.get("page", 1) for s in slides),
        "slides": slides,
        "reveals": reveals,
        "animate": animate or set(),
        "exam": next((s for s in slides if s["kind"] == "your_turn"), {}),
        "answer": next((s for s in slides if s["kind"] == "model"), {}),
    }


