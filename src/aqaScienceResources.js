function qualify(fileName) {
  if (fileName.includes("8461")) return { level: "GCSE/IGCSE", subject: "Biology" };
  if (fileName.includes("8462")) return { level: "GCSE/IGCSE", subject: "Chemistry" };
  if (fileName.includes("8463")) return { level: "GCSE/IGCSE", subject: "Physics" };
  if (fileName.includes("7401") || fileName.includes("7402")) return { level: "A-Level", subject: "Biology" };
  if (fileName.includes("7407") || fileName.includes("7408")) return { level: "A-Level", subject: "Physics" };
  return null;
}

function seriesLabel(code) {
  if (!code) return "Sample assessment";
  const season = code.startsWith("JUN") ? "June" : "November";
  return `${season} 20${code.slice(-2)}`;
}

function describe(fileName) {
  const specTitle = SPEC_TITLES[fileName];
  if (specTitle) {
    return { category: "Specifications", title: specTitle, seriesLabel: "Specification" };
  }

  const match = fileName.match(/^AQA-([A-Z0-9]+)-(SQP|SMS|QP|W-MS|MS|INS|WRE)(?:-(JUN\d+|NOV\d+))?\.PDF$/);
  if (!match) return null;
  const [, paperId, kind, seriesCode] = match;
  const paperTitle = PAPER_TITLES[paperId];
  if (!paperTitle) return null;

  if (kind === "QP" || kind === "SQP") {
    return {
      category: "Past Questions",
      title: kind === "SQP" ? `Sample ${paperTitle}` : paperTitle,
      seriesLabel: seriesLabel(seriesCode),
    };
  }
  if (kind === "INS") {
    const title = paperId === "74083" ? paperTitle : `${paperTitle} — data booklet`;
    return { category: "Past Questions", title, seriesLabel: seriesLabel(seriesCode) };
  }
  if (kind === "MS" || kind === "W-MS" || kind === "SMS") {
    return {
      category: "Mark Schemes",
      title: kind === "SMS" ? `Sample ${paperTitle}` : paperTitle,
      seriesLabel: seriesLabel(seriesCode),
    };
  }
  if (kind === "WRE") {
    return { category: "Examiner Reports", title: paperTitle, seriesLabel: seriesLabel(seriesCode) };
  }
  return null;
}

function item(path) {
  const fileName = path.split("/").pop();
  const meta = qualify(fileName);
  const described = describe(fileName);
  if (!meta || !described) return null;
  return {
    level: meta.level,
    subject: meta.subject,
    exam_board: "AQA",
    resource_category: described.category,
    title: described.title,
    file_name: fileName,
    series_label: described.seriesLabel,
    file_url_override: `${FILESTORE}/${path}`,
  };
}

